import { expect, test } from "@playwright/test";

const RUN_PREBUILT_E2E = process.env.PREBUILT_SQL_E2E === "1";

type EngineClient = typeof import("../../src/lib/engine/engine-client");
type Viewdef = typeof import("../../src/lib/engine/viewdef");
type Measures = typeof import("../../src/lib/fhir/measures");
type Cohorts = typeof import("../../src/lib/fhir/cohorts");
type Prebuilt = typeof import("../../src/lib/engine/prebuilt");

interface Comparison {
  name: string;
  equal: boolean;
  liveLength: number;
  prebuiltLength: number;
  firstDifference?: string;
}

/**
 * The app obtains its SQL from fhir4ds two ways: translated live in the
 * browser (the default build), or translated at build time by
 * `npm run prebuild:sql` (scripts/prebuild_sql.py, desktop Python) and
 * shipped under /fhir4ds/prebuilt/. The two must give the same SQL, or the
 * prebuilt build would compute something other than what the live build
 * shows.
 *
 * This spec translates everything live in the real engine — the main
 * window's Python for CQL, the engine frame's Python for views, libraries
 * and the OMOP composition — and compares it with the generated files.
 *
 * It needs the real engine, a dev server in live mode and the generated
 * files, so it is opt-in:
 *
 *   npm run prebuild:sql
 *   PREBUILT_SQL_E2E=1 PLAYWRIGHT_PORT=<port> npx playwright test tests/e2e/prebuilt-sql.spec.ts
 */
test("prebuilt SQL is identical to live translation in the real engine", async ({ page }) => {
  test.skip(!RUN_PREBUILT_E2E, "Set PREBUILT_SQL_E2E=1 after `npm run prebuild:sql`, with a dev server in live mode.");
  test.setTimeout(420_000);

  // A quiet page: it loads the app shell and the isolated document the
  // engine needs, without a patient's records.
  await page.goto("/settings");

  const comparisons = await page.evaluate(async () => {
    // Indirect dynamic import, so the function's bundler leaves it alone.
    const loadModule = (path: string): Promise<unknown> => new Function("p", "return import(p)")(path);
    const client = (await loadModule("/src/lib/engine/engine-client.ts")) as EngineClient;
    const viewdef = (await loadModule("/src/lib/engine/viewdef.ts")) as Viewdef;
    const measures = (await loadModule("/src/lib/fhir/measures.ts")) as Measures;
    const cohorts = (await loadModule("/src/lib/fhir/cohorts.ts")) as Cohorts;
    const prebuilt = (await loadModule("/src/lib/engine/prebuilt.ts")) as Prebuilt;

    const generated = await fetch(`${prebuilt.prebuiltBaseUrl()}/manifest.json`, { cache: "no-cache" }).then((response) => response.json());
    if (generated.generator !== "fhir4px-prebuild-sql") throw new Error("public/fhir4ds/prebuilt is missing; run `npm run prebuild:sql`");

    const results: Comparison[] = [];
    const compare = (name: string, live: string, built: string) => {
      let firstDifference: string | undefined;
      if (live !== built) {
        let index = 0;
        while (index < live.length && live[index] === built[index]) index += 1;
        firstDifference = `at ${index}: live ${JSON.stringify(live.slice(index, index + 60))} vs prebuilt ${JSON.stringify(built.slice(index, index + 60))}`;
      }
      results.push({ name, equal: live === built, liveLength: live.length, prebuiltLength: built.length, firstDifference });
    };
    const builtText = async (file: string): Promise<string> => {
      const response = await fetch(`${prebuilt.prebuiltBaseUrl()}/${file}`, { cache: "no-cache" });
      if (!response.ok) throw new Error(`prebuilt ${file}: ${response.status}`);
      return response.text();
    };
    const builtJson = async (file: string): Promise<unknown> => JSON.parse(await builtText(file));

    // Quality measures: live for one year, against the template with that year filled in.
    const inputs = await measures.loadMeasureTranslationInputs();
    const year = new Date().getFullYear();
    const period = { start: `${year}-01-01T00:00:00.000Z`, end: `${year}-12-31T23:59:59.999Z` };
    for (const id of Object.keys(generated.measures)) {
      const live = await viewdef.translateMeasureSql(inputs.measureCql[id] ?? "", inputs.libraryTexts, period);
      const built = prebuilt.fillMeasurementYear(await builtText(generated.measures[id].file), generated.yearPlaceholder, year);
      compare(`measure ${id}`, live, built);
    }

    // Cohort libraries.
    for (const definition of cohorts.COHORT_DEFINITIONS) {
      compare(`cohort ${definition.id}`, await viewdef.translateCqlToSql(definition.cql), await builtText(generated.cohorts[definition.id].file));
    }

    // Views, libraries and the composition are generated by the engine
    // frame's own Python, so the live side runs in the frame. The app creates
    // the frame on its first engine call.
    await client.engineQuery("SELECT 1");
    const frame = [...document.querySelectorAll("iframe")].find((candidate) => candidate.src.endsWith("engine.html"));
    if (!frame?.contentWindow) throw new Error("engine frame not found");
    // `eval` lives on the global object, which the DOM lib types separately.
    const frameWindow = frame.contentWindow as Window & typeof globalThis;
    const frameViewdef = (await frameWindow.eval('import("/src/lib/engine/viewdef.ts")')) as Viewdef;

    const viewManifest = await fetch("/fhir4ds/uscore-views/manifest.json").then((response) => response.json());
    for (const view of viewManifest.views) {
      const viewDefinition = await fetch(`/fhir4ds/uscore-views/${view.id}.json`).then((response) => response.json());
      const live = await frameViewdef.generateViewSql(viewDefinition);
      const built = (await builtJson(generated.views[view.id].file)) as { sql: string; setup_sql: string[] };
      compare(`view ${view.id}`, JSON.stringify([live.sql, live.setup_sql ?? []]), JSON.stringify([built.sql, built.setup_sql]));
    }

    for (const id of Object.keys(generated.omopLibraries)) {
      const library = await fetch(`/fhir4ds/omop-libraries/${id}.json`).then((response) => response.json());
      const live = await frameViewdef.generateLibrarySql(library);
      const built = (await builtJson(generated.omopLibraries[id].file)) as { sql: string };
      compare(`omop library ${id}`, live.sql ?? "", built.sql);
    }

    // The composition asks the engine's DuckDB for each view's column names.
    // The app stages its resources table before running the composition, so
    // the table exists for the views; do the same (no patient needed).
    await client.engineQuery("CREATE OR REPLACE TEMP TABLE __vd_src (resource JSON)");
    await client.engineQuery("INSERT INTO __vd_src SELECT NULL WHERE false");
    // The live function creates the schema and the base views through its
    // callback and returns only the final statements. The engine runs the
    // whole sequence, so the generated file must equal all of it. The same
    // callback also carries the function's own read-only column probes
    // ("SELECT ... LIMIT 0"), which are not setup: keep the CREATEs.
    const executed: string[] = [];
    const returned = await frameViewdef.deriveCompositionDdl(async (sql: string) => {
      executed.push(sql);
      const probed = await client.engineQuery(sql);
      return { schema: { fields: probed.columns.map((name) => ({ name })) } };
    });
    const setup = executed.filter((sql) => /^CREATE /i.test(sql));
    compare("omop setup (schema, base views, composition)", JSON.stringify([...setup, ...returned]), JSON.stringify(await builtJson(generated.omopComposition.file)));

    return results;
  });

  expect(comparisons.filter((comparison) => !comparison.equal)).toEqual([]);
  expect(comparisons.length).toBeGreaterThan(20);
});
